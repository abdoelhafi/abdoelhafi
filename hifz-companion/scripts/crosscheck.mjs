#!/usr/bin/env node
// Compares the bundled text with an independent republication of the KFGQPC Warsh data
// and writes reports/crosscheck.json and reports/crosscheck.md.
//
// Usage: node scripts/crosscheck.mjs <path to a checkout of the cross-check repository>
//
// The report lists ayah references and Unicode code points only. It never reproduces or
// "corrects" text: deciding which reading is right is a job for a qualified teacher.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bodyWithoutDigitMark, bodyWithoutGlyphMark, countBySurah, readJson, sha256File } from './lib.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const otherRoot = process.argv[2];
if (!otherRoot) {
  console.error('Usage: node scripts/crosscheck.mjs <path to cross-check source checkout>');
  process.exit(2);
}

const pin = readJson(join(root, 'data/source.json')).crossCheck;
const otherPath = join(otherRoot, pin.textFile);
if (sha256File(otherPath) !== pin.textSha256) {
  console.error(`Cross-check file checksum mismatch for ${pin.textFile}. Update data/source.json deliberately.`);
  process.exit(1);
}

const ours = readJson(join(root, 'data/warsh.json'));
const theirs = readJson(otherPath);
const theirByRef = new Map(theirs.map((r) => [`${r.sura_no}:${r.aya_no}`, r]));

const ourCounts = countBySurah(ours.ayahs, 'surah', 'ayah');
const theirCounts = countBySurah(theirs, 'sura_no', 'aya_no');
const countMismatches = [];
for (let s = 1; s <= 114; s++) {
  if (ourCounts[s] !== theirCounts[s]) countMismatches.push({ surah: s, ours: ourCounts[s], theirs: theirCounts[s] });
}

const hex = (s) => [...s].map((c) => 'U+' + c.codePointAt(0).toString(16).toUpperCase().padStart(4, '0'));

// Smallest differing span, as code points, for the report.
function span(a, b) {
  const x = [...a];
  const y = [...b];
  let i = 0;
  while (i < x.length && i < y.length && x[i] === y[i]) i++;
  let j = 0;
  while (j < x.length - i && j < y.length - i && x[x.length - 1 - j] === y[y.length - 1 - j]) j++;
  return { ours: hex(x.slice(i, x.length - j).join('')), theirs: hex(y.slice(i, y.length - j).join('')) };
}

// Comparison-only form: no whitespace, canonical mark order. Never displayed.
const squash = (t) => t.replace(/\s+/g, '').normalize('NFD');

const categories = { identical: [], spacingOnly: [], markOrderOnly: [], spacingAndMarkOrder: [], substantive: [], missing: [] };
for (const a of ours.ayahs) {
  const ref = `${a.surah}:${a.ayah}`;
  const other = theirByRef.get(ref);
  if (!other) {
    categories.missing.push({ ref });
    continue;
  }
  const x = bodyWithoutGlyphMark(a.text);
  const y = bodyWithoutDigitMark(other.aya_text);
  if (x === y) categories.identical.push(ref);
  else if (x.replace(/\s+/g, '') === y.replace(/\s+/g, '')) categories.spacingOnly.push(ref);
  // Canonically equivalent: the same marks, stored in a different order. Renders the same.
  else if (x.normalize('NFD') === y.normalize('NFD')) categories.markOrderOnly.push(ref);
  else if (squash(x) === squash(y)) categories.spacingAndMarkOrder.push(ref);
  else categories.substantive.push({ ref, ...span(squash(x), squash(y)) });
}

const report = {
  ours: ours.source,
  theirs: { repository: pin.repository, commit: pin.commit, file: pin.textFile, sha256: pin.textSha256 },
  ayahCount: { ours: ours.ayahs.length, theirs: theirs.length },
  verseCountMismatches: countMismatches,
  summary: Object.fromEntries(Object.entries(categories).map(([k, v]) => [k, v.length])),
  spacingOnly: categories.spacingOnly,
  markOrderOnly: categories.markOrderOnly,
  spacingAndMarkOrder: categories.spacingAndMarkOrder,
  substantive: categories.substantive,
  missing: categories.missing,
};
writeFileSync(join(root, 'reports/crosscheck.json'), JSON.stringify(report, null, 2) + '\n');

const md = [
  '# Cross-check: bundled text vs. KFGQPC Warsh v10',
  '',
  'Generated by `scripts/crosscheck.mjs`. Ayah-number marks are excluded (the two versions encode them differently).',
  '',
  `- Ayahs: ${report.ayahCount.ours} bundled, ${report.ayahCount.theirs} in v10`,
  `- Per-surah verse count mismatches: ${countMismatches.length}`,
  `- Identical: ${report.summary.identical}`,
  `- Spacing only (an extra or missing space; same letters and marks): ${report.summary.spacingOnly}`,
  `- Mark order only (canonically equivalent, renders the same): ${report.summary.markOrderOnly}`,
  `- Spacing and mark order together: ${report.summary.spacingAndMarkOrder}`,
  `- **Substantive differences (need a teacher's review): ${report.summary.substantive}**`,
  `- Missing in v10: ${report.summary.missing}`,
  '',
  '## Substantive differences',
  '',
  'Each row shows only the differing code points, compared with spaces removed and marks in canonical order. Compare the ayah in both versions against a printed Warsh mushaf.',
  '',
  '| Ayah | Bundled (v2.1) | v10 |',
  '|---|---|---|',
  ...categories.substantive.map((d) => {
    const cell = (cps) => (cps.length === 0 ? '(nothing)' : cps.length > 8 ? `${cps.slice(0, 8).join(' ')} … (${cps.length} code points)` : cps.join(' '));
    return `| ${d.ref} | ${cell(d.ours)} | ${cell(d.theirs)} |`;
  }),
  '',
];
writeFileSync(join(root, 'reports/crosscheck.md'), md.join('\n'));

console.log(JSON.stringify(report.summary), 'verse count mismatches:', countMismatches.length);
